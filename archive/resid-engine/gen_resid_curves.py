"""Write src/resid/curves.h: the "Bright" cut-off curves for reSID 0.16, i.e. reSIDfp's measured
cut-off curves (libsidplayfp / Sidplay3 at its default filter setting, 0.5), as reSID fc_point
lists (cut-off register 0-2047 -> Hz) for the 6581 and the 8580.

Input: tools/filter_measurements/reSIDfp_6581_res0.txt and reSIDfp_8580_res0.txt (white noise
through the low-pass filter, resonance 0, -3 dB point at fc = 0, 8, ..., 2040; each line
"subtune fc cutoffHz peakdB").  reSID's two-pole filter has its -3 dB point at the frequency it is
given (Q = 0.707 at resonance 0), so the measured frequencies are used as they are: kept rising
(measurement noise), capped at 18 kHz, with fc 2047 equal to fc 2040.  The core loads a curve with
reSID's own fc_plotter() / interpolate(), as reSID builds its default curves.
Usage: python tools/gen_resid_curves.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = os.path.join(ROOT, 'tools', 'filter_measurements')


def points(name):
    pts, top = [], 0
    for line in open(os.path.join(M, name)):
        song, fc, hz, pk = line.split()
        top = max(top, min(int(float(hz)), 18000))
        pts.append((int(fc), top))
    pts.append((2047, top))
    return pts


def fmt(name, pts):
    # reSID's interpolate() wants the first and last points repeated
    pts = [pts[0]] + pts + [pts[-1]]
    rows = []
    for i in range(0, len(pts), 6):
        rows.append('  ' + ', '.join('{ %4d, %5d }' % p for p in pts[i:i + 6]) + ',')
    return 'static const fc_point %s[%d] =\n{\n%s\n};\n' % (name, len(pts), '\n'.join(rows))


out = os.path.join(ROOT, 'src', 'resid', 'curves.h')
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_resid_curves.py from tools/filter_measurements: do not edit.\n'
            "// reSIDfp's measured cut-off curves (6581, 8580) as reSID fc_point lists, first and last\n"
            '// points repeated for interpolate().\n'
            '#ifndef SIDPLAYER_RESID_CURVES_H\n#define SIDPLAYER_RESID_CURVES_H\n\n')
    f.write(fmt('brightCurve6581', points('reSIDfp_6581_res0.txt')) + '\n')
    f.write(fmt('brightCurve8580', points('reSIDfp_8580_res0.txt')))
    f.write('\n#endif\n')
print('wrote', out)
