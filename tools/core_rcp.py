"""Split build/blob/sidcore.bin into Palm resources ('armc' 1, 2, ...; each under 64 KB) and write
build/palm/core.rcp, which the app's resource file includes.  The app reads them back as one stream.
Usage: python tools/core_rcp.py [core.bin out-folder]   (default build/blob/sidcore.bin build/palm)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHUNK = 60000
src = open(sys.argv[1] if len(sys.argv) > 2 else os.path.join(ROOT, "build", "blob", "sidcore.bin"), "rb").read()
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "build", "palm")
os.makedirs(out, exist_ok=True)
lines = ["// Generated by tools/core_rcp.py: the ARM sound core, split into resources."]
for n, i in enumerate(range(0, len(src), CHUNK), 1):
    name = "armc%04d.bin" % n
    open(os.path.join(out, name), "wb").write(src[i:i + CHUNK])
    lines.append('DATA "armc" ID %d "%s"' % (n, name))
open(os.path.join(out, "core.rcp"), "w", newline="\n").write("\n".join(lines) + "\n")
print("core: %d bytes in %d resources" % (len(src), n))
