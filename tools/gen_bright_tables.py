"""Write src/core/brighttables.h: libsidplay's low-pass coefficient tables for the "Bright" filter
curve, which follows reSIDfp's measured cutoff curves (Sidplay3 / libsidplayfp at its default
filter setting, curve 0.5): one table for the 6581, one for the 8580.

Inputs, tools/filter_measurements/ (white noise through the low-pass filter, resonance 0, at every
cutoff setting fc = 0, 8, ..., 2040; each line "subtune fc cutoffHz peakdB"):
  reSIDfp_6581_res0.txt, reSIDfp_8580_res0.txt   reSIDfp's -3 dB cutoff
  libsidplay1_default_res0.txt                   libsidplay's cutoff with its default curve, which
                                                 gives its response: coefficient -> cutoff
For every fc the script finds the coefficient that gives reSIDfp's cutoff (log-log interpolation
of libsidplay's measured response; points every 8 settings, log interpolation between them), at
44100 Hz and clamped to 0.01..1 as libsidplay clamps its own table.  The core scales the table for
other sample rates as libsidplay scales its own (x 44100 / rate).

The tables are stored as IEEE single-precision bit patterns, so every build (PC, ARM, simulator)
uses exactly the same values.  Usage: python tools/gen_bright_tables.py
(The Sidplay3 fork's libsidplay 1 uses the same header.)
"""
import math
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = os.path.join(ROOT, 'tools', 'filter_measurements')


def load(name):
    out = {}
    for line in open(os.path.join(M, name)):
        song, fc, hz, pk = line.split()
        out[int(fc)] = float(hz)
    return out


def default_dy(fc):
    d = math.exp(fc / 2048.0 * math.log(400.0)) / 60.0 + 0.05   # libsidplay: Fs 400, Fm 60, Ft 0.05
    return min(1.0, max(0.01, d))


ls = load('libsidplay1_default_res0.txt')
resp, top = [], 0.0
for d, hz in sorted((default_dy(fc), hz) for fc, hz in ls.items() if hz < 19000):   # 20000 = open
    top = max(top, hz)            # keep the response rising (measurement noise)
    resp.append((d, top))
MAX_HZ = resp[-1][1]


def dy_for(hz):
    """libsidplay coefficient that gives cutoff `hz` at 44100 Hz."""
    if hz >= 19000 or hz > MAX_HZ:
        return 1.0
    d0, h0 = resp[0]
    if hz <= h0:
        return max(0.01, d0 * hz / h0)
    for (d1, h1), (d2, h2) in zip(resp, resp[1:]):
        if h1 <= hz <= h2:
            if h2 == h1:
                return d1
            t = (math.log(hz) - math.log(h1)) / (math.log(h2) - math.log(h1))
            return math.exp(math.log(d1) + t * (math.log(d2) - math.log(d1)))
    return 1.0


def table(name):
    cur = load(name)
    pts, top = [], 0.0
    for fc in range(0, 2048, 8):
        top = max(top, cur[fc])   # keep the curve rising
        pts.append(dy_for(top))
    pts.append(pts[-1])           # fc 2047
    out = []
    for fc in range(2048):
        i, t = fc >> 3, (fc & 7) / 8.0
        d = math.exp(math.log(pts[i]) + t * (math.log(pts[i + 1]) - math.log(pts[i])))
        d = min(1.0, max(0.01, d))
        out.append(struct.unpack('<I', struct.pack('<f', d))[0])
    return out


lines = ["// Generated by tools/gen_bright_tables.py from tools/filter_measurements: do not edit.",
         "// libsidplay's low-pass filter table for the \"Bright\" curve: reSIDfp's measured cutoff curves",
         "// (6581 and 8580) at 44100 Hz, as IEEE single-precision bit patterns.",
         "#ifndef SIDPLAYER_BRIGHTTABLES_H", "#define SIDPLAYER_BRIGHTTABLES_H", "",
         "static const unsigned long brightTableRate = 44100;",
         "static const unsigned long brightTableBits[2][0x800] = {"]
for chip, name in (("6581", 'reSIDfp_6581_res0.txt'), ("8580", 'reSIDfp_8580_res0.txt')):
    t = table(name)
    lines.append("  { // %s" % chip)
    for i in range(0, 2048, 8):
        lines.append("    " + ", ".join("0x%08x" % v for v in t[i:i + 8]) + ",")
    lines.append("  },")
lines += ["};", "", "#endif", ""]
out = os.path.join(ROOT, 'src', 'core', 'brighttables.h')
with open(out, 'w', newline='\n') as f:
    f.write("\n".join(lines))
print('wrote', out)
