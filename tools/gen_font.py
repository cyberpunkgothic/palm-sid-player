"""Write src/palm_c64/font8.h: the 8x8 C64-style font (from tools/mock_c64.py) as a C table.

Codes 32..95 are ASCII (the app maps lower case to upper case); 128.. are the graphics characters
listed in GFX_CODES.  Each glyph is 8 bytes, top row first, bit 7 = leftmost pixel.
Usage: python tools/gen_font.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mock_c64 import glyph

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GFX_CODES = ["█", "▌", "─", "│", "┌", "┐", "└", "┘",
             "├", "┤", "▶", "■", "░", "▲", "▼", "‖"]
NAMES = ["FULL", "LEFTHALF", "HLINE", "VLINE", "TOPLEFT", "TOPRIGHT", "BOTLEFT", "BOTRIGHT",
         "TEE_RIGHT", "TEE_LEFT", "PLAY", "STOP", "DIM", "UP", "DOWN", "PAUSE"]


def rows(ch):
    g = glyph(ch)
    return [sum(1 << (7 - x) for x in range(8) if g[y][x]) for y in range(8)]


lines = ["/* Generated by tools/gen_font.py from the font in tools/mock_c64.py: do not edit.", " *",
         " * 8x8 C64-style font (our own drawing).  font8[c - 32] for ASCII 32..95; gfx8[] for the",
         " * graphics characters G_*.  Bit 7 of each byte is the leftmost pixel. */",
         "#ifndef FONT8_H", "#define FONT8_H", ""]
for i, n in enumerate(NAMES):
    lines.append("#define G_%-10s ((char)%d)" % (n, 128 + i))
lines += ["", "static const UInt8 font8[64][8] = {"]
for c in range(32, 96):
    ch = chr(c)
    rep = {"\\": "?", "[": "(", "]": ")", "^": "?", "@": "?", "%": "?"}.get(ch, ch)
    lines.append("\t{ %s },  /* %s */" % (", ".join("0x%02x" % b for b in rows(rep)),
                                         repr(ch).replace("*/", "* /")))
lines += ["};", "", "static const UInt8 gfx8[%d][8] = {" % len(GFX_CODES)]
for ch, n in zip(GFX_CODES, NAMES):
    lines.append("\t{ %s },  /* G_%s */" % (", ".join("0x%02x" % b for b in rows(ch)), n))
lines += ["};", "", "#endif", ""]
open(os.path.join(ROOT, "src", "palm_c64", "font8.h"), "w", newline="\n").write("\n".join(lines))
print("wrote src/palm_c64/font8.h")
