"""Write src/core/filtertables.h: libsidplay's low-pass filter table for the default filter settings,
exactly as the PC reference build (build/pc/sid2wav_ref.exe) computes it.

Why: the table is built with exp() and log(), whose last bits differ between C libraries, so the ARM
build would get a slightly different table (645 of 2048 entries differ) and occasionally a different
output sample.  With the PC's table built in, the ARM build matches the PC reference bit for bit.
Run after tools/pc_build.bat ref:  python tools/gen_filter_tables.py
"""
import os, struct, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RATES = [44100, 22050]
TUNE = os.path.join(ROOT, "tests", "tunes", "user", "Elite.sid")     # (any PSID tune: only its set-up is used)


def table(rate):
    out = os.path.join(ROOT, "build", "test", "tables_%d.bin" % rate)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run([os.path.join(ROOT, "build", "pc", "sid2wav_ref.exe"), TUNE, "-r", str(rate),
                    "-tables", out], check=True, stdout=subprocess.DEVNULL)
    data = open(out, "rb").read()
    return struct.unpack("<2048I", data[:2048 * 4])     # the low-pass table comes first


lines = ["// Generated by tools/gen_filter_tables.py from build/pc/sid2wav_ref.exe: do not edit.",
         "// libsidplay's low-pass filter table (filterTable) for the default filter settings",
         "// (Fs 400, Fm 60, Ft 0.05), as IEEE single-precision bit patterns.",
         "#ifndef SIDPLAYER_FILTERTABLES_H", "#define SIDPLAYER_FILTERTABLES_H", "",
         "static const unsigned long filterTableRates[] = { %s };" % ", ".join(map(str, RATES)),
         "static const unsigned long filterTableBits[%d][0x800] = {" % len(RATES)]
for r in RATES:
    t = table(r)
    lines.append("  { // %d Hz" % r)
    for i in range(0, 2048, 8):
        lines.append("    " + ", ".join("0x%08x" % v for v in t[i:i + 8]) + ",")
    lines.append("  },")
lines += ["};", "", "#endif", ""]
with open(os.path.join(ROOT, "src", "core", "filtertables.h"), "w", newline="\n") as f:
    f.write("\n".join(lines))
print("wrote src/core/filtertables.h for", RATES)
